"""Local browser gamepad for lemoGamePad ultimate.

Serves a self-contained page over HTTP and receives controller input over a
WebSocket. Everything stays on the local network: the page has no external
scripts, fonts, analytics or CDN links, and this module never contacts the
internet.

The page is protected by a short pairing key generated by the server. The key
is part of the URL printed in the console and in the QR code, so a device that
has not been paired cannot drive the virtual pad. WebSocket upgrades are also
checked against the Origin header to block cross-site connections from a
website opened in the same browser.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import struct
import sys
import threading
import urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from typing import Callable, Optional

WS_GUID = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11"
MAX_PAYLOAD = 64 * 1024
CSP = (
    "default-src 'self'; "
    "script-src 'self'; "
    "style-src 'self'; "
    "img-src 'self' data:; "
    "connect-src 'self' ws: wss:; "
    "base-uri 'none'; "
    "form-action 'none'; "
    "frame-ancestors 'none'"
)

# Only these files are served. Anything else in the folder stays private.
STATIC = {
    "/": ("index.html", "text/html; charset=utf-8"),
    "/index.html": ("index.html", "text/html; charset=utf-8"),
    "/app.js": ("app.js", "text/javascript; charset=utf-8"),
    "/style.css": ("style.css", "text/css; charset=utf-8"),
    "/favicon.svg": ("favicon.svg", "image/svg+xml"),
}


def asset_dir() -> str:
    """Where the bundled HTML/CSS/JS live, both in git and inside PyInstaller."""
    base = getattr(sys, "_MEIPASS", None)
    if base:
        return os.path.join(base, "web")
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "web")


def _clamp(value, low: int, high: int) -> int:
    try:
        number = int(value)
    except (TypeError, ValueError):
        return low if low > 0 else 0
    return max(low, min(high, number))


def _accept_key(key: str) -> str:
    digest = hashlib.sha1((key + WS_GUID).encode("ascii")).digest()
    return base64.b64encode(digest).decode("ascii")


class WebGamepadServer:
    """
    HTTP + WebSocket endpoint for browser controllers.

    [on_input] is called with (token, ip, state, want_slot, send_rumble) and
    must return the 1-based assigned pad (0 when the server is full).
    [on_ping] returns the current pad, [on_close] releases the token, and
    [on_token] returns a fresh, unused peer token.
    """

    def __init__(
        self,
        port: int,
        key: str,
        on_input: Callable,
        on_ping: Callable,
        on_close: Callable,
        on_token: Callable,
        log: Optional[Callable[[str], None]] = None,
    ):
        self.port = port
        self.key = key
        self.on_input = on_input
        self.on_ping = on_ping
        self.on_close = on_close
        self.on_token = on_token
        self.log = log or print
        self.enabled = False
        self.error = ""
        self.running = False
        self._httpd: Optional[ThreadingHTTPServer] = None
        self._thread: Optional[threading.Thread] = None
        self._connections: set = set()
        self._connections_lock = threading.Lock()

    # ---------------------------------------------------------------- lifecycle
    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self.running = True
        self._thread = threading.Thread(
            target=self._serve, name="lemo-web", daemon=True
        )
        self._thread.start()

    def stop(self) -> None:
        self.running = False
        httpd = self._httpd
        self._httpd = None
        if httpd is not None:
            try:
                httpd.shutdown()
            except Exception:
                pass
            try:
                httpd.server_close()
            except Exception:
                pass
        with self._connections_lock:
            connections, self._connections = list(self._connections), set()
        for connection in connections:
            connection.close()
        thread = self._thread
        if thread is not None and thread.is_alive():
            thread.join(timeout=1.0)

    def _serve(self) -> None:
        try:
            httpd = _QuietHTTPServer(("0.0.0.0", self.port), _Handler)
        except OSError as exc:
            self.error = f"browser pad port {self.port} unavailable ({exc})"
            self.log(f"browser pad disabled: {self.error}")
            return
        httpd.web = self
        httpd.daemon_threads = True
        self._httpd = httpd
        self.enabled = True
        self.log(f"browser pad ready on http://0.0.0.0:{self.port} (local network only)")
        try:
            httpd.serve_forever(poll_interval=0.25)
        except Exception as exc:  # pragma: no cover - socket torn down
            if self.running:
                self.error = f"browser pad stopped ({exc})"
        finally:
            self.enabled = False
            try:
                httpd.server_close()
            except Exception:
                pass

    # -------------------------------------------------------------- connections
    def _track(self, connection: "_Connection") -> None:
        with self._connections_lock:
            self._connections.add(connection)

    def _untrack(self, connection: "_Connection") -> None:
        with self._connections_lock:
            self._connections.discard(connection)

    def submit(self, connection: "_Connection", state: dict, want_slot: int) -> int:
        try:
            return int(self.on_input(connection.token, connection.ip, state, want_slot, connection.send_rumble))
        except Exception as exc:
            self.log(f"browser input failed: {exc}")
            return 0

    def ping(self, connection: "_Connection") -> int:
        try:
            return int(self.on_ping(connection.token))
        except Exception as exc:
            self.log(f"browser ping failed: {exc}")
            return 0

    def closed(self, connection: "_Connection") -> None:
        try:
            self.on_close(connection.token)
        except Exception as exc:
            self.log(f"browser disconnect failed: {exc}")


class _QuietHTTPServer(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def handle_error(self, request, client_address):
        # A browser closing a tab is not an error. Logging a traceback for
        # every disconnect would bury the useful console lines.
        pass


class _Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"
    server_version = "lemoGamePad"
    sys_version = ""

    @property
    def web(self) -> WebGamepadServer:
        return self.server.web  # type: ignore[attr-defined]

    def log_message(self, fmt, *args):  # noqa: A003 - stdlib signature
        return

    def do_GET(self):  # noqa: N802 - stdlib signature
        parsed = urllib.parse.urlsplit(self.path)
        query = urllib.parse.parse_qs(parsed.query)
        given = (query.get("k") or [""])[0]
        if not given or not hmac.compare_digest(given, self.web.key):
            self._plain(
                401,
                "Pairing link is not valid.\n"
                "Open the browser pad URL printed by lemoGamePad-server.\n",
            )
            return

        if parsed.path == "/ws":
            self._websocket()
            return

        item = STATIC.get(parsed.path)
        if item is None:
            self._plain(404, "Not found\n")
            return
        self._file(*item)

    def do_POST(self):  # noqa: N802 - stdlib signature
        self._plain(405, "Method not allowed\n")

    # ------------------------------------------------------------------ helpers
    def _headers(self, status: int, content_type: str, length: int) -> None:
        self.send_response(status)
        self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(length))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Referrer-Policy", "no-referrer")
        self.send_header("Content-Security-Policy", CSP)
        self.end_headers()

    def _plain(self, status: int, message: str) -> None:
        body = message.encode("utf-8")
        self._headers(status, "text/plain; charset=utf-8", len(body))
        try:
            self.wfile.write(body)
        except OSError:
            pass

    def _file(self, name: str, content_type: str) -> None:
        path = os.path.join(asset_dir(), name)
        try:
            with open(path, "rb") as handle:
                body = handle.read()
        except OSError:
            self._plain(500, "The browser pad files are missing from this build.\n")
            return
        self._headers(200, content_type, len(body))
        try:
            self.wfile.write(body)
        except OSError:
            pass

    # ---------------------------------------------------------------- websocket
    def _websocket(self) -> None:
        if self.headers.get("Upgrade", "").lower() != "websocket":
            self._plain(400, "Expected a WebSocket upgrade\n")
            return
        if self.headers.get("Sec-WebSocket-Version", "") != "13":
            self._plain(426, "WebSocket version 13 required\n")
            return
        key = self.headers.get("Sec-WebSocket-Key", "")
        if not key:
            self._plain(400, "Missing Sec-WebSocket-Key\n")
            return
        if not self._origin_ok():
            self._plain(403, "Cross-site browser control is not allowed\n")
            return

        self.send_response(101, "Switching Protocols")
        self.send_header("Upgrade", "websocket")
        self.send_header("Connection", "Upgrade")
        self.send_header("Sec-WebSocket-Accept", _accept_key(key))
        self.end_headers()
        self.wfile.flush()
        self.close_connection = True

        connection = _Connection(
            self.connection, self.client_address[0], self.web
        )
        connection.run()

    def _origin_ok(self) -> bool:
        """Reject a page served from a different host (cross-site WebSocket)."""
        origin = self.headers.get("Origin")
        if not origin:
            return True
        host = self.headers.get("Host", "")
        try:
            parts = urllib.parse.urlsplit(origin)
        except ValueError:
            return False
        if parts.scheme not in ("http", "https"):
            return False
        return parts.netloc.lower() == host.lower()


class _Connection:
    """One browser tab: parses WebSocket frames and forwards pad input."""

    def __init__(self, sock, ip: str, web: WebGamepadServer):
        self.sock = sock
        self.ip = ip
        self.web = web
        self.token = int(web.on_token())
        self.seq = 0
        self.slot = 0
        self.closed = False
        self._finished = False
        self._send_lock = threading.Lock()
        self._fragment = b""
        self._fragment_opcode: Optional[int] = None
        self.name = f"browser {self.token & 0xFF:02X}"

    # ------------------------------------------------------------------ frames
    def _recv(self, size: int) -> bytes:
        data = bytearray()
        while len(data) < size:
            chunk = self.sock.recv(size - len(data))
            if not chunk:
                raise EOFError("browser closed the connection")
            data.extend(chunk)
        return bytes(data)

    def _read_frame(self):
        first = self._recv(2)
        fin = bool(first[0] & 0x80)
        opcode = first[0] & 0x0F
        masked = bool(first[1] & 0x80)
        length = first[1] & 0x7F
        if length == 126:
            length = struct.unpack(">H", self._recv(2))[0]
        elif length == 127:
            length = struct.unpack(">Q", self._recv(8))[0]
        if length > MAX_PAYLOAD:
            raise ValueError("browser frame is too large")
        if not masked:
            raise ValueError("browser frame is not masked")
        mask = self._recv(4)
        body = self._recv(length)
        payload = bytes(byte ^ mask[index % 4] for index, byte in enumerate(body))
        return fin, opcode, payload

    def _send(self, opcode: int, payload: bytes) -> None:
        header = bytearray([0x80 | opcode])
        length = len(payload)
        if length < 126:
            header.append(length)
        elif length < 65536:
            header.append(126)
            header.extend(struct.pack(">H", length))
        else:
            header.append(127)
            header.extend(struct.pack(">Q", length))
        with self._send_lock:
            self.sock.sendall(bytes(header) + payload)

    def send_json(self, message: dict) -> None:
        try:
            self._send(0x1, json.dumps(message, separators=(",", ":")).encode("utf-8"))
        except OSError:
            self.closed = True

    def send_rumble(self, small: int, large: int) -> None:
        self.send_json(
            {
                "t": "r",
                "s": _clamp(small, 0, 255),
                "l": _clamp(large, 0, 255),
            }
        )

    # ------------------------------------------------------------------- input
    def _message(self, payload: bytes) -> None:
        try:
            message = json.loads(payload.decode("utf-8"))
        except (UnicodeDecodeError, ValueError):
            return
        if not isinstance(message, dict):
            return

        kind = message.get("t")
        if kind == "p":
            slot = self.web.ping(self)
            if slot != self.slot:
                self.slot = slot
                self.send_json({"t": "s", "n": slot})
            self.send_json({"t": "q", "c": message.get("c"), "n": slot})
            return

        # Anything else is controller state. Unknown fields are ignored, so an
        # older page keeps working against a newer server and vice versa.
        self.seq = (self.seq + 1) & 0xFFFF
        state = {
            "buttons": _clamp(message.get("b"), 0, 0x1FFFF),
            "lx": _clamp(message.get("lx"), -32768, 32767),
            "ly": _clamp(message.get("ly"), -32768, 32767),
            "rx": _clamp(message.get("rx"), -32768, 32767),
            "ry": _clamp(message.get("ry"), -32768, 32767),
            "l2": _clamp(message.get("l2"), 0, 255),
            "r2": _clamp(message.get("r2"), 0, 255),
            "battery": 100,
            "seq": self.seq,
        }
        slot = self.web.submit(self, state, _clamp(message.get("w"), 0, 8))
        if slot != self.slot:
            self.slot = slot
            self.send_json({"t": "s", "n": slot})

    # -------------------------------------------------------------------- loop
    def run(self) -> None:
        self.web._track(self)
        self.web.log(f"browser connected: {self.ip}")
        try:
            while not self.closed:
                fin, opcode, payload = self._read_frame()
                if opcode == 0x8:  # close
                    try:
                        self._send(0x8, payload[:125])
                    except OSError:
                        pass
                    break
                if opcode == 0x9:  # ping
                    self._send(0xA, payload)
                    continue
                if opcode == 0xA:  # pong
                    continue
                if opcode == 0x0:  # continuation of a fragmented message
                    if self._fragment_opcode is None:
                        continue
                    payload = self._fragment + payload
                    opcode = self._fragment_opcode
                    self._fragment = b""
                    self._fragment_opcode = None
                if not fin:
                    self._fragment = payload
                    self._fragment_opcode = opcode
                    continue
                if opcode == 0x2:  # binary is not used by the page
                    continue
                if opcode == 0x1:
                    self._message(payload)
        except (EOFError, OSError, ValueError):
            pass
        finally:
            self._finish()

    def _finish(self) -> None:
        if self._finished:
            return
        self._finished = True
        self.closed = True
        self.web._untrack(self)
        self.web.closed(self)
        self.web.log(f"browser disconnected: {self.ip}")
        try:
            self.sock.close()
        except OSError:
            pass

    def close(self) -> None:
        self.closed = True
        try:
            self.sock.shutdown(2)
        except OSError:
            pass
        try:
            self.sock.close()
        except OSError:
            pass
